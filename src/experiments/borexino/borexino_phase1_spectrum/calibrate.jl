# Calibrate the Phase-I low-energy detector response on Borexino's fitted ⁷Be component (PRL 107, 141302, Fig. 1 top).
#
# The ⁷Be ν–e recoil spectrum (Newtrinos fluxes, cross section and survival probability at the default parameters) is
# folded with E = s·T + a and σ = c √(T/MeV) and fitted, with a free normalisation, to Borexino's ⁷Be component as drawn
# (45.5 cpd/100 t). Calibrating on the component avoids the ⁷Be–⁸⁵Kr degeneracy of a fit to the total. Writes
# data/calibration.txt with (s, a, c), the normalisation and the background normalisations (1: Borexino's components).
#
#   cd src/experiments/borexino/borexino_phase1_spectrum && julia --project=../../../.. calibrate.jl
using Newtrinos, Optim, Printf
const B = Newtrinos.borexino_ph1_spectrum
const SC = Newtrinos.solar_common

physics = B.default_physics()
physics = (; physics.osc, physics.solar_flux, physics.solar_xsec, physics.earth_layers)
params = Newtrinos.get_params(physics)
le = B.read_spectra().le
site = SC.Site(physics, 42.45; depth_km=1.4)
sf = physics.solar_flux
l7 = sf.lines.be7
P7 = SC.averaged_prob(physics, site, :be7, l7.E, params)[:, 1]
i384, i862 = findfirst(e -> abs(e - 0.3843) < 1e-3, l7.E), findfirst(e -> abs(e - 0.8613) < 1e-3, l7.E)
Φ7 = sf.flux(:be7, params)
sel = le.be7 .> 0
target = le.be7[sel]

function be7_counts(s, a, c)
    bins = [((lo - a) / s * 1e-3, (hi - a) / s * 1e-3) for (lo, hi) in zip(le.lo, le.hi)]
    reso(Etot) = c / s * 1e-3 * sqrt(max(Etot - Newtrinos.solar_xsec.M_E, 1e-4))
    r = SC.ESResponse(physics.solar_xsec, [l7.E[i384], l7.E[i862]], bins, reso; scale_unc=0.0, reso_unc=0.0, T_step=0.002)
    K = r.K[:nominal]
    w = [Φ7 * l7.br[i384], Φ7 * l7.br[i862]]
    (K.e * (w .* [P7[i384], P7[i862]]) .+ K.x * (w .* (1 .- [P7[i384], P7[i862]]))) .* (B.ELECTRONS_PER_100T * B.DAY * B.EXPOSURE_LE)
end
# x = [norm, s, a [keV], c [keV]]; Poisson deviance on the curve counts
function dev(x)
    (x[2] <= 0.5 || x[4] <= 1) && return Inf
    μ = x[1] .* be7_counts(x[2], x[3], x[4])[sel] .+ 1e-9
    2 * sum(μ .- target .+ target .* log.(target ./ μ))
end
best = nothing
for a0 in (-20.0, 0.0, 20.0), c0 in (30.0, 50.0)
    r = optimize(dev, [1.0, 1.0, a0, c0], NelderMead(), Optim.Options(iterations=4000, g_tol=1e-10))
    (best === nothing || Optim.minimum(r) < Optim.minimum(best)) && (global best = r)
end
x = Optim.minimizer(best)
rate7 = SC.es_interaction_rate(physics, site, SC.ESTotal(physics, :be7), params) * B.ELECTRONS_PER_100T * B.DAY
@printf "deviance w.r.t. Borexino's ⁷Be component: %.3f (%d bins of curve counts)\n" Optim.minimum(best) count(sel)
@printf "E = %.4f T + %.1f keV, σ = %.1f keV √(T/MeV); normalisation %.4f → Borexino's ⁷Be rate %.2f vs Newtrinos %.2f cpd/100 t\n" x[2] x[3] x[4] x[1] x[1] * rate7 rate7
open(joinpath(B.DATADIR, "calibration.txt"), "w") do io
    println(io, "# Generated by calibrate.jl: low-energy response E = scale · T + offset [keV], σ = smear · √(T/MeV) [keV], fitted to")
    println(io, "# Borexino's ⁷Be component (PRL 107, 141302, Fig. 1 top); be7_norm = Borexino / Newtrinos ⁷Be rate at the defaults;")
    println(io, "# background normalisations: 1 = Borexino's fitted components")
    for (k, v) in vcat([:scale => x[2], :offset => x[3], :smear => x[4], :be7_norm => x[1]], [k => 1.0 for k in keys(B.BACKGROUNDS)])
        @printf io "%s %.6g\n" k v
    end
end
