# Calibrate the energy response of the Borexino MC shapes on Borexino's best-fit spectrum.
#
# Fits Borexino's best-fit model of the TFC-subtracted spectrum (recovered from the published
# residuals) with the MC shapes, an energy scale, offset and additional smearing, with CNO fixed
# at the best fit (6.6 cpd/100 t), pep constrained to 2.74 ± 0.04, pp fixed at 131.1 and ⁸B at
# the Newtrinos default prediction, as in the Borexino fit. Writes data/calibration.txt with the
# response and the fitted rates (backgrounds: used as defaults and prior centres).
#
#   cd src/experiments/borexino/borexino_phase3 && julia --project=../../../.. calibrate.jl
using Newtrinos, Optim, ADTypes, ForwardDiff, Printf
const B = Newtrinos.borexino_ph3
const SC = Newtrinos.solar_common

spec = B.read_spectrum()
fine = B.fine_densities()
names = vcat(collect(keys(B.SOLAR)), collect(keys(B.BACKGROUNDS)))
@assert maximum(abs.(spec.lo[2:end] .- spec.hi[1:end-1])) < 0.02 "data bins not contiguous"

# ⁸B at the default parameters, resolution 45 keV/√MeV (it is nearly flat)
physics = B.default_physics()
physics = (; physics.osc, physics.solar_flux, physics.solar_xsec, physics.earth_layers)
params = Newtrinos.get_params(physics)
site = SC.Site(physics, 42.45; depth_km=1.4)
E_b8 = collect(range(0.4, 16.5, length=200))
resp = SC.ESResponse(physics.solar_xsec, E_b8, collect(zip(spec.lo .* 1e-3, spec.hi .* 1e-3)),
                     Etot -> 45e-3 * sqrt(max(Etot - Newtrinos.solar_xsec.M_E, 1e-3)); scale_unc=0.01, reso_unc=0.1)
Pe = SC.averaged_prob(physics, site, :b8, E_b8, params)[:, 1]
b8 = SC.es_rates(resp, physics.solar_flux.spectrum(:b8, E_b8, params), Pe) .* (B.ELECTRONS_PER_100T * B.DAY * B.EXPOSURE)
@printf "⁸B: %.1f events in the window\n" sum(b8)

const IPP, IPEP, ICNO, IBI = 1, 3, 4, 5
fixed = Dict(IPP => 131.1, ICNO => 6.6)
function nll(θ, target)
    r = exp.(clamp.(θ[1:11], -15, 8))
    r = [haskey(fixed, i) ? oftype(r[i], fixed[i]) : r[i] for i in eachindex(r)]
    T = B.templates(fine, spec.lo, spec.hi, 1 + θ[12] / 100, 10θ[13], 10abs(θ[14]))
    μ = B.EXPOSURE .* (T * r) .+ b8 .+ 1e-9
    l = sum(μ .- target .* log.(μ)) + 0.5 * ((r[IPEP] - 2.74) / 0.04)^2
    r[IBI] > 10.8 && (l += 0.5 * ((r[IBI] - 10.8) / 1.0)^2)
    l
end
θ0 = vcat(log.([131.1, 48.0, 2.74, 6.6, 10.0, 2.0, 5.0, 20.0, 4.0, 1.0, 5.0]), 0.0, 0.0, 4.5)
res = optimize(θ -> nll(θ, spec.bestfit), θ0, LBFGS(), Optim.Options(iterations=3000, g_tol=1e-6); autodiff=ADTypes.AutoForwardDiff())
θ = Optim.minimizer(res)
sat = sum(spec.bestfit .- spec.bestfit .* log.(spec.bestfit))
r = [haskey(fixed, i) ? fixed[i] : exp(θ[i]) for i in 1:11]
cal = vcat([:scale => 1 + θ[12] / 100, :offset => 10θ[13], :smear => 10abs(θ[14])], [n => v for (n, v) in zip(names, r)])
@printf "deviance w.r.t. Borexino best fit: %.2f (%d bins)\n" 2 * (Optim.minimum(res) - sat) length(spec.E)
open(joinpath(B.DATADIR, "calibration.txt"), "w") do io
    println(io, "# Generated by calibrate.jl: energy response (E = offset [keV] + scale · E_mc, extra smearing [keV/√MeV])")
    println(io, "# and rates [cpd/100 t] fitted to Borexino's best-fit TFC-subtracted spectrum (CNO fixed, pp fixed)")
    for (k, v) in cal
        @printf io "%s %.6g\n" k v
        @printf "  %-10s %.4g\n" k v
    end
end
