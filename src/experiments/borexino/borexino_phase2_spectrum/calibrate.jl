# Calibrate the energy response of the Borexino MC shapes on Borexino's Phase-II best-fit spectrum.
#
# Fits Borexino's best-fit model of the TFC-subtracted spectrum (Nature 2018 Fig. 2a, from the published residuals)
# with the solar MC shapes (pp, ⁷Be, pep free; CNO fixed at the HZ value 4.92 cpd/100 t as in Borexino's fit; ⁸B at the
# Newtrinos default), the Borexino background components with free normalisations, and an energy scale, offset and
# additional smearing of the solar shapes; ¹⁴C and pile-up with Borexino's constraints (±5 %, ±2 %). Writes data/calibration.txt
# with the response, the fitted solar rates and the background normalisations (used as defaults).
#
#   cd src/experiments/borexino/borexino_phase2_spectrum && julia --project=../../../.. calibrate.jl
using Newtrinos, Optim, ADTypes, ForwardDiff, Printf
const B = Newtrinos.borexino_ph2_spectrum
const SC = Newtrinos.solar_common

spec = B.read_spectrum()
fine = B.fine_densities()
physics = B.default_physics()
physics = (; physics.osc, physics.solar_flux, physics.solar_xsec, physics.earth_layers)
params = Newtrinos.get_params(physics)
site = SC.Site(physics, 42.45; depth_km=1.4)
E_b8 = collect(range(0.4, 16.5, length=200))
resp = SC.ESResponse(physics.solar_xsec, E_b8, collect(zip(spec.lo .* 1e-3, spec.hi .* 1e-3)),
                     Etot -> 0.05 * sqrt(max(Etot - Newtrinos.solar_xsec.M_E, 1e-3)); scale_unc=0.01, reso_unc=0.1)
Pe = SC.averaged_prob(physics, site, :b8, E_b8, params)[:, 1]
b8 = SC.es_rates(resp, physics.solar_flux.spectrum(:b8, E_b8, params), Pe) .* (B.ELECTRONS_PER_100T * B.DAY * B.EXPOSURE)
@printf "⁸B: %.1f events in the window\n" sum(b8)

const NS, NB = length(B.SOLAR), length(B.BACKGROUNDS)
const ICNO = 4
# θ = [log solar rates (4); log background normalisations (NB); scale [%]; offset [10 keV]; smear [10 keV/√MeV]]
function model(θ)
    r = [i == ICNO ? oftype(θ[i], 4.92) : exp(clamp(θ[i], -15, 8)) for i in 1:NS]
    m = exp.(clamp.(θ[NS+1:NS+NB], -15, 3))
    T = B.borexino_ph3.templates(fine, spec.lo, spec.hi, 1 + θ[end-2] / 100, 10θ[end-1], 10abs(θ[end]))
    B.EXPOSURE .* (T * r .+ spec.bkg * m) .+ b8 .+ 1e-9
end
# ¹⁴C (±5 %) and pile-up (±2.0 %) normalisations with Borexino's constraints, as in the module
const ICP = [(NS + findfirst(==(k), keys(B.BACKGROUNDS)), w) for (k, w) in ((:c14, 0.05), (:pileup, 2.8 / 137.5))]
nll(θ, target) = (μ = model(θ); sum(μ .- target .* log.(μ)) + sum(((exp(θ[i]) - 1) / w)^2 / 2 for (i, w) in ICP))
θ0 = vcat(log.([131.1, 48.0, 2.74, 4.92]), zeros(NB), 0.0, 0.0, 0.5)
opt(f, x) = optimize(f, x, LBFGS(linesearch = Optim.LineSearches.BackTracking()), Optim.Options(iterations=4000, g_tol=1e-6);
                     autodiff=ADTypes.AutoForwardDiff())
res = opt(θ -> nll(θ, spec.bestfit), θ0)
θ = Optim.minimizer(res)
sat = sum(spec.bestfit .- spec.bestfit .* log.(spec.bestfit))
@printf "deviance w.r.t. Borexino best fit: %.2f (%d bins)\n" 2 * (Optim.minimum(res) - sat) length(spec.E)
rates = [i == ICNO ? 4.92 : exp(θ[i]) for i in 1:NS]
cal = vcat([:scale => 1 + θ[end-2] / 100, :offset => 10θ[end-1], :smear => 10abs(θ[end])],
           [k => v for (k, v) in zip(keys(B.SOLAR), rates)],
           [k => exp(θ[NS+j]) for (j, k) in enumerate(keys(B.BACKGROUNDS))])
open(joinpath(B.DATADIR, "calibration.txt"), "w") do io
    println(io, "# Generated by calibrate.jl: energy response of the solar MC shapes (E = offset [keV] + scale · E_mc, extra")
    println(io, "# smearing [keV/√MeV]), solar rates [cpd/100 t] and background normalisations (1 = Borexino's fitted component)")
    println(io, "# fitted to Borexino's best-fit Phase-II TFC-subtracted spectrum (CNO fixed at 4.92)")
    for (k, v) in cal
        @printf io "%s %.6g\n" k v
        @printf "  %-8s %.4g\n" k v
    end
end
